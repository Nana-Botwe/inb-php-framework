<?php

declare(strict_types=1);

namespace Core\Database\Grammars;

use Core\Database\ColumnDefinition;
use Core\Database\ForeignKeyDefinition;

/** Oracle Database 12c+ (identity columns, OFFSET/FETCH). */
class OracleGrammar extends Grammar
{
    public function name(): string
    {
        return 'oci';
    }

    public function random(): string
    {
        return 'DBMS_RANDOM.VALUE';
    }

    public function insertIdStrategy(): string
    {
        return 'returning_into';
    }

    public function sessionStatements(): array
    {
        // Dates are exchanged as "Y-m-d H:i:s" strings everywhere in the framework.
        return [
            "ALTER SESSION SET NLS_DATE_FORMAT = 'YYYY-MM-DD HH24:MI:SS'",
            "ALTER SESSION SET NLS_TIMESTAMP_FORMAT = 'YYYY-MM-DD HH24:MI:SS'",
        ];
    }

    public function compileTables(): array
    {
        return ['SELECT table_name AS name FROM user_tables ORDER BY table_name', [], 'name'];
    }

    public function compileColumns(string $table): array
    {
        return ['SELECT column_name AS name FROM user_tab_columns WHERE table_name = ? ORDER BY column_id', [$table], 'name'];
    }

    protected function compileAddColumn(string $table, ColumnDefinition $column): string
    {
        return "ALTER TABLE $table ADD (" . $this->compileColumn($column) . ')';
    }

    /** Older Oracle versions have no "DROP TABLE IF EXISTS": ignore ORA-00942 (table does not exist). */
    public function compileDropIfExists(string $table): string
    {
        $statement = 'DROP TABLE ' . $this->wrap($table) . ' CASCADE CONSTRAINTS';

        return "BEGIN EXECUTE IMMEDIATE '" . str_replace("'", "''", $statement) . "'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;";
    }

    /** Oracle has no ON UPDATE actions, and RESTRICT/NO ACTION is its default behaviour. */
    protected function foreignActions(ForeignKeyDefinition $fk): string
    {
        return in_array($fk->onDelete, ['CASCADE', 'SET NULL'], true) ? ' ON DELETE ' . $fk->onDelete : '';
    }

    protected function autoIncrementType(ColumnDefinition $column): string
    {
        return ($column->type === 'bigInteger' ? 'NUMBER(19)' : 'NUMBER(10)') . ' GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY';
    }

    public function type(ColumnDefinition $column): string
    {
        $o = $column->options;

        return match ($column->type) {
            'string', 'enum' => 'VARCHAR2(' . (int) ($o['length'] ?? 255) . ' CHAR)',
            'char' => 'CHAR(' . (int) $o['length'] . ' CHAR)',
            'text', 'mediumText', 'longText', 'json' => 'CLOB',
            'integer' => 'NUMBER(10)',
            'tinyInteger' => 'NUMBER(3)',
            'smallInteger' => 'NUMBER(5)',
            'bigInteger' => 'NUMBER(19)',
            'boolean' => 'NUMBER(1)',
            'decimal' => sprintf('NUMBER(%d,%d)', $o['precision'], $o['scale']),
            'float' => 'BINARY_FLOAT',
            'double' => 'BINARY_DOUBLE',
            'dateTime', 'timestamp' => 'TIMESTAMP(0)',
            'time' => 'VARCHAR2(8)',
            'year' => 'NUMBER(4)',
            default => parent::type($column),
        };
    }
}
