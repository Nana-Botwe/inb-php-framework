<?php

declare(strict_types=1);

namespace Core\Database\Grammars;

use Core\Database\ColumnDefinition;

/** PostgreSQL 10+ */
class PostgresGrammar extends Grammar
{
    public function name(): string
    {
        return 'pgsql';
    }

    public function compileLimitOffset(?int $limit, ?int $offset, bool $hasOrders): string
    {
        return ($limit !== null ? ' LIMIT ' . $limit : '') . ($offset !== null ? ' OFFSET ' . $offset : '');
    }

    /** Case-insensitive like MySQL's default collation. */
    public function likeOperator(): string
    {
        return 'ILIKE';
    }

    /** Backslash is PostgreSQL's default LIKE escape character. */
    public function likeEscape(): string
    {
        return '';
    }

    public function insertIdStrategy(): string
    {
        return 'returning';
    }

    public function compileTables(): array
    {
        return ['SELECT tablename AS name FROM pg_catalog.pg_tables WHERE schemaname = current_schema() ORDER BY tablename', [], 'name'];
    }

    public function compileColumns(string $table): array
    {
        return ['SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position', [$table], 'name'];
    }

    protected function compileAddColumn(string $table, ColumnDefinition $column): string
    {
        return "ALTER TABLE $table ADD COLUMN " . $this->compileColumn($column);
    }

    /** CASCADE removes dependent foreign keys, so tables can be dropped in any order. */
    public function compileDropAllTables(array $tables): array
    {
        return $tables === [] ? [] : ['DROP TABLE IF EXISTS ' . implode(', ', array_map(fn ($t) => $this->wrap($t), $tables)) . ' CASCADE'];
    }

    /** PostgreSQL booleans need TRUE/FALSE, not 1/0. */
    public function literal(mixed $value, ?ColumnDefinition $column = null): string
    {
        if ($column !== null && $column->type === 'boolean' && ($value === true || $value === false || $value === 0 || $value === 1 || $value === '0' || $value === '1')) {
            return (bool) $value ? 'TRUE' : 'FALSE';
        }

        return parent::literal($value, $column);
    }

    protected function autoIncrementType(ColumnDefinition $column): string
    {
        return ($column->type === 'bigInteger' ? 'BIGINT' : 'INTEGER') . ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
    }

    public function type(ColumnDefinition $column): string
    {
        return match ($column->type) {
            'dateTime', 'timestamp' => 'TIMESTAMP(0) WITHOUT TIME ZONE',
            'time' => 'TIME(0) WITHOUT TIME ZONE',
            'json' => 'JSONB',
            default => parent::type($column),
        };
    }
}
